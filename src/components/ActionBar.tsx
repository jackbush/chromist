import { useEffect, useRef, useState } from 'react'
import type { Pin, Settings } from '../types'
import { SettingsPopover } from './SettingsPopover'

type Props = {
  pins: Pin[]
  settings: Settings
  onSettingsChange: (settings: Settings) => void
}

export function ActionBar({ pins, settings, onSettingsChange }: Props) {
  const [open, setOpen] = useState(false)
  const wrapRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    if (!open) return

    const onPointerDown = (e: PointerEvent) => {
      if (!wrapRef.current?.contains(e.target as Node)) setOpen(false)
    }
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') setOpen(false)
    }

    document.addEventListener('pointerdown', onPointerDown)
    document.addEventListener('keydown', onKeyDown)
    return () => {
      document.removeEventListener('pointerdown', onPointerDown)
      document.removeEventListener('keydown', onKeyDown)
    }
  }, [open])

  return (
    <header className="bar">
      <h1 className="bar-title">palette</h1>
      <div className="bar-settings" ref={wrapRef}>
        <button
          type="button"
          className="bar-cog"
          aria-label="Settings"
          aria-expanded={open}
          aria-haspopup="dialog"
          onClick={() => setOpen((v) => !v)}
        >
          <Cog />
        </button>
        {open && (
          <SettingsPopover pins={pins} settings={settings} onChange={onSettingsChange} />
        )}
      </div>
    </header>
  )
}

